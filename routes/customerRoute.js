const router=require('express').Router();
const Customer=require('../models/customerModel');
const verifyToken=require('../middlewares/tokenVerification');
const {tenantMiddleware}=require('../middlewares/tenantMiddleware');
const requireRole=require('../middlewares/requireRole');
const {normalizeName,writeCustomer}=require('../services/customers/customerService');
router.use(verifyToken,tenantMiddleware);
const scope=req=>({tenantId:req.tenantId,clientId:req.clientId||'default'});
const error=(e,res,next)=>{if(e.code===11000)return res.status(409).json({success:false,code:'PHONE_ALREADY_EXISTS'});if(e.status)return res.status(e.status).json({success:false,code:e.message});return next(e);};
router.get('/access',(req,res)=>res.json({canDelete:Boolean(req.tenantId)&&['Owner','Admin'].includes(req.scope?.membership?.role)}));
router.get('/',async(req,res,next)=>{try{
 const s=scope(req);if(!s.tenantId)return res.status(403).json({code:'TENANT_REQUIRED'});
 const q=normalizeName(req.query.q),rawLimit=Number(req.query.limit),limit=Number.isFinite(rawLimit)&&rawLimit>0?Math.min(rawLimit,50):20;
 const filter={...s,isActive:{$ne:false}};
 const list=await Customer.find(filter).sort({createdAt:-1}).lean();
 const data=list.filter(c=>!q||[c.name,c.phone,c.address,c.taxIdentity?.value,c.taxIdentity?.valueNormalized].some(v=>normalizeName(v).includes(q))||Boolean(Customer.normalizePhone(q)&&Customer.normalizePhone(c.phone).includes(Customer.normalizePhone(q)))).slice(0,limit);
 return res.json({success:true,data});
 }catch(e){return error(e,res,next);}});
router.post('/',async(req,res,next)=>{try{const data=await writeCustomer({...scope(req),body:req.body});return res.status(201).json({success:true,data});}catch(e){return error(e,res,next);}});
router.patch('/:id',async(req,res,next)=>{try{const data=await writeCustomer({...scope(req),id:req.params.id,body:req.body});return res.json({success:true,data});}catch(e){return error(e,res,next);}});
router.delete('/:id',requireRole('Owner','Admin'),async(req,res,next)=>{try{const data=await writeCustomer({...scope(req),id:req.params.id,deactivate:true});return res.json({success:true,data});}catch(e){return error(e,res,next);}});
module.exports=router;
